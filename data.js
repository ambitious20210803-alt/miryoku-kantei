// 判定：A-Fの最多型。同点は前半の早い設問を優先（安定）
function diagnose(frontAns, backAns){
  const score = {A:0,B:0,C:0,D:0,E:0,F:0};
  const weight = {}; TYPE_ORDER.forEach((t,i)=>weight[t]=0);
  frontAns.forEach((ai,qi)=>{
    const t = QUESTIONS_FRONT[qi].choices[ai].t;
    score[t]++;
    weight[t] += (5-qi); // 早い設問ほど重い
  });
  if(Array.isArray(backAns)){
    backAns.forEach((ai,qi)=>{
      if(ai==null) return;
      const t = QUESTIONS_BACK[qi].choices[ai].t;
      score[t]++;
    });
  }
  let best="A", bestScore=-1, bestW=-1;
  TYPE_ORDER.forEach(t=>{
    if(score[t]>bestScore || (score[t]===bestScore && weight[t]>bestW)){
      best=t; bestScore=score[t]; bestW=weight[t];
    }
  });
  return { key:best, type:TYPES[best], score };
}
